'use strict';
const fs=require('fs'),path=require('path'),assert=require('node:assert/strict');
const {chromium}=require('playwright-core');
const root=path.resolve(__dirname,'..');
const base=(process.env.AVATAR_BASE_URL||'http://127.0.0.1:8010').replace(/\/$/,'');
const out=path.join(root,'docs/media');
const result={ok:false,captured_at:new Date().toISOString(),source:'actual running workstation; no mocked responses',checks:[],screenshots:[]};
let context,page;
(async()=>{try{
 fs.mkdirSync(path.join(root,'cache/tmp'),{recursive:true});
 context=await chromium.launchPersistentContext(path.join(root,'cache/character-capture'),{executablePath:process.env.CHROME_PATH||'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true,viewport:{width:1440,height:1080},env:{...process.env,TEMP:path.join(root,'cache/tmp'),TMP:path.join(root,'cache/tmp')},args:['--no-proxy-server']});
 page=context.pages()[0]||await context.newPage();
 await page.goto(base,{waitUntil:'domcontentloaded',timeout:30000});
 await page.waitForFunction(()=>document.getElementById('serviceStatus')?.textContent==='服务已就绪',null,{timeout:20000});
 assert((await page.title()).includes('林知夏'));
 assert((await page.locator('#characterSubtitle').textContent()).includes('林知夏'));
 assert((await page.locator('#characterLabel').textContent()).includes('女A'));
 assert((await page.locator('#scriptText').inputValue()).includes('林知夏'));
 const status=await page.evaluate(async()=>await(await fetch('/api/studio/status')).json());
 assert.equal(status.character.name,'林知夏');assert.equal(status.avatar_id,'student_dorm_motion_bank_v3');assert(status.ready);
 result.checks.push('studio title, identity labels and default speech use 林知夏','original prepared avatar ID and ready media service preserved');
 await page.screenshot({path:path.join(out,'female-a-studio.png'),fullPage:true});result.screenshots.push('female-a-studio.png');
 await page.goto(base+'/character',{waitUntil:'domcontentloaded',timeout:30000});
 await page.waitForFunction(()=>document.getElementById('archiveStatus')?.textContent.includes('归档包已就绪'),null,{timeout:20000});
 await page.waitForFunction(()=>Array.from(document.images).every(image=>image.complete&&image.naturalWidth>0));
 const portraitRatio=await page.locator('.portrait').evaluate(image=>image.getBoundingClientRect().width/image.getBoundingClientRect().height);
 assert(Math.abs(portraitRatio-9/16)<0.002);
 const record=await page.evaluate(async()=>await(await fetch('/api/studio/character')).json());
 assert.equal(record.character.scene.name,'知夏的日光宿舍');assert(record.download_ready);
 assert.equal(record.archive.counts.selected_motion_clips,48);assert.equal(record.archive.counts.independent_pose_images,28);
 const download=await context.request.get(base+'/character/archive.zip',{headers:{Range:'bytes=0-3'}});
 assert.equal(download.status(),206);assert.equal((await download.body()).toString('hex'),'504b0304');
 result.checks.push('paired scene and complete archive inventory exposed','portrait keeps its 9:16 proportions','archive download returns an actual ZIP with HTTP range support');
 await page.screenshot({path:path.join(out,'female-a-archive.png'),fullPage:true});result.screenshots.push('female-a-archive.png');
 await page.setViewportSize({width:390,height:844});await page.screenshot({path:path.join(out,'female-a-mobile.png'),fullPage:true});result.screenshots.push('female-a-mobile.png');
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 result.checks.push('390-pixel mobile page has no horizontal overflow');
 result.character_id=record.character.id;result.archive_source_files_at_capture=record.archive.file_count;result.ok=true;
}catch(error){result.error=error.message;process.exitCode=1;}
finally{if(context)await context.close();fs.writeFileSync(path.join(out,'female-a-capture.json'),JSON.stringify(result,null,2)+'\n');console.log(JSON.stringify(result));}})();
